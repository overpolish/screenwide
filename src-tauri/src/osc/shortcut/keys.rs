/// Physical DOM key codes shared by the macOS and Windows native overlays.
/// Escape remains reserved for cancellation; modifier-only bindings cannot
/// produce the key-down/key-up pair required by held overlay tools.
pub(super) fn codes(code: &str) -> Option<(u16, u16)> {
  Some(match code {
    "Enter" => (0x24, 0x0d),
    "Equal" => (0x18, 0xbb),
    "KeyA" => (0x00, 0x41),
    "KeyS" => (0x01, 0x53),
    "KeyD" => (0x02, 0x44),
    "KeyF" => (0x03, 0x46),
    "KeyH" => (0x04, 0x48),
    "KeyG" => (0x05, 0x47),
    "KeyZ" => (0x06, 0x5a),
    "KeyX" => (0x07, 0x58),
    "KeyC" => (0x08, 0x43),
    "KeyV" => (0x09, 0x56),
    "KeyB" => (0x0b, 0x42),
    "KeyQ" => (0x0c, 0x51),
    "KeyW" => (0x0d, 0x57),
    "KeyE" => (0x0e, 0x45),
    "KeyR" => (0x0f, 0x52),
    "KeyY" => (0x10, 0x59),
    "KeyT" => (0x11, 0x54),
    "Digit1" => (0x12, 0x31),
    "Digit2" => (0x13, 0x32),
    "Digit3" => (0x14, 0x33),
    "Digit4" => (0x15, 0x34),
    "Digit6" => (0x16, 0x36),
    "Digit5" => (0x17, 0x35),
    "Digit9" => (0x19, 0x39),
    "Digit7" => (0x1a, 0x37),
    "Minus" => (0x1b, 0xbd),
    "Digit8" => (0x1c, 0x38),
    "Digit0" => (0x1d, 0x30),
    "BracketRight" => (0x1e, 0xdd),
    "KeyO" => (0x1f, 0x4f),
    "KeyU" => (0x20, 0x55),
    "BracketLeft" => (0x21, 0xdb),
    "KeyI" => (0x22, 0x49),
    "KeyP" => (0x23, 0x50),
    "KeyL" => (0x25, 0x4c),
    "KeyJ" => (0x26, 0x4a),
    "Quote" => (0x27, 0xde),
    "KeyK" => (0x28, 0x4b),
    "Semicolon" => (0x29, 0xba),
    "Backslash" => (0x2a, 0xdc),
    "Comma" => (0x2b, 0xbc),
    "Slash" => (0x2c, 0xbf),
    "KeyN" => (0x2d, 0x4e),
    "KeyM" => (0x2e, 0x4d),
    "Period" => (0x2f, 0xbe),
    "Tab" => (0x30, 0x09),
    "Space" => (0x31, 0x20),
    "Backquote" => (0x32, 0xc0),
    "Backspace" => (0x33, 0x08),
    "F17" => (0x40, 0x80),
    "NumpadDecimal" => (0x41, 0x6e),
    "NumpadMultiply" => (0x43, 0x6a),
    "NumpadAdd" => (0x45, 0x6b),
    "PrintScreen" => (0x46, 0x2c),
    "NumpadDivide" => (0x4b, 0x6f),
    "NumpadEnter" => (0x4c, 0x0d),
    "NumpadSubtract" => (0x4e, 0x6d),
    "F18" => (0x4f, 0x81),
    "F19" => (0x50, 0x82),
    "NumpadEqual" => (0x51, 0xbb),
    "Numpad0" => (0x52, 0x60),
    "Numpad1" => (0x53, 0x61),
    "Numpad2" => (0x54, 0x62),
    "Numpad3" => (0x55, 0x63),
    "Numpad4" => (0x56, 0x64),
    "Numpad5" => (0x57, 0x65),
    "Numpad6" => (0x58, 0x66),
    "Numpad7" => (0x59, 0x67),
    "F20" => (0x5a, 0x83),
    "Numpad8" => (0x5b, 0x68),
    "Numpad9" => (0x5c, 0x69),
    "F5" => (0x60, 0x74),
    "F6" => (0x61, 0x75),
    "F7" => (0x62, 0x76),
    "F3" => (0x63, 0x72),
    "F8" => (0x64, 0x77),
    "F9" => (0x65, 0x78),
    "F11" => (0x67, 0x7a),
    "F13" => (0x69, 0x7c),
    "F16" => (0x6a, 0x7f),
    "F14" => (0x6b, 0x7d),
    "F10" => (0x6d, 0x79),
    "F12" => (0x6f, 0x7b),
    "F15" => (0x71, 0x7e),
    "Insert" => (0x72, 0x2d),
    "Home" => (0x73, 0x24),
    "PageUp" => (0x74, 0x21),
    "Delete" => (0x75, 0x2e),
    "F4" => (0x76, 0x73),
    "End" => (0x77, 0x23),
    "F2" => (0x78, 0x71),
    "PageDown" => (0x79, 0x22),
    "F1" => (0x7a, 0x70),
    "ArrowLeft" => (0x7b, 0x25),
    "ArrowRight" => (0x7c, 0x27),
    "ArrowDown" => (0x7d, 0x28),
    "ArrowUp" => (0x7e, 0x26),
    _ => return None,
  })
}
